    func path(in rect: CGRect) -> Path {
        var result = Path()
        guard let first = points.first else { return result }
        let scale = min(rect.width, rect.height / 2.03)
        let width = scale
        let height = scale * 2.03
        let left = rect.midX - width / 2
        let top = rect.midY - height / 2
        result.move(to: CGPoint(x: left + first.x * width, y: top + first.y * height))
        for point in points.dropFirst() {
            result.addLine(to: CGPoint(x: left + point.x * width, y: top + point.y * height))
        }
        result.closeSubpath()
        return result
    }
